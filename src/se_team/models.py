"""
Pydantic data models for structured handoffs across the software engineering team.
No free-form text is passed between agents where a structured schema is possible.
"""

from __future__ import annotations

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class DataSchemaField(BaseModel):
    """Field definition for database schema."""
    name: str = Field(..., description="Column or attribute name")
    type: str = Field(..., description="Data type (e.g., INTEGER, REAL, TEXT, TIMESTAMP)")
    constraints: str = Field(default="", description="Constraints (e.g., PRIMARY KEY AUTOINCREMENT, NOT NULL)")
    description: str = Field(default="", description="Field purpose and business rules")


class DataSchema(BaseModel):
    """Database table or document schema."""
    table_name: str = Field(..., description="Table name in SQLite database")
    description: str = Field(..., description="Table purpose and relations")
    fields: List[DataSchemaField] = Field(default_factory=list, description="Columns and field definitions")


class APIEndpoint(BaseModel):
    """API contract specification for an endpoint."""
    path: str = Field(..., description="Endpoint path (e.g., /api/calculate, /api/history)")
    method: Literal["GET", "POST", "PUT", "DELETE", "PATCH"] = Field(..., description="HTTP method")
    summary: str = Field(..., description="Short summary of endpoint purpose")
    request_body_schema: Optional[Dict[str, Any]] = Field(default=None, description="Expected JSON request payload schema")
    response_body_schema: Dict[str, Any] = Field(..., description="Expected JSON response schema")
    status_codes: Dict[int, str] = Field(default_factory=lambda: {200: "Success", 400: "Validation Error", 500: "Internal Server Error"})


class SpecialistPrompt(BaseModel):
    """Tailored context and instructions generated by the Orchestrator for a specialist agent."""
    role: str = Field(..., description="Target specialist role name")
    target_workspace_dir: str = Field(..., description="Relative destination folder (e.g., frontend/, backend/)")
    instructions: str = Field(..., description="Precise technical instructions and requirements")
    files_to_produce: List[str] = Field(..., description="List of expected file paths")


class SpecPackage(BaseModel):
    """
    Complete specification package generated by the Orchestrator & Product Lead.
    Forms the source of truth for Frontend and Backend implementations.
    """
    project_name: str = Field(..., description="Name of the application")
    brief_summary: str = Field(..., description="Summary of the user brief (Thai or English)")
    task_scope: str = Field(..., description="In-scope and out-of-scope boundaries")
    acceptance_criteria: List[str] = Field(..., description="Clear, verifiable acceptance criteria")
    data_schemas: List[DataSchema] = Field(default_factory=list, description="SQLite database schema specifications")
    api_contract: List[APIEndpoint] = Field(default_factory=list, description="REST API contract definitions")
    frontend_prompt: SpecialistPrompt = Field(..., description="Tailored instructions for Frontend Specialist")
    backend_prompt: SpecialistPrompt = Field(..., description="Tailored instructions for Backend Specialist")
    qa_guidance: str = Field(..., description="Calculation rules, boundary checks, and expected formulas for QA")


class BugReport(BaseModel):
    """Detailed record of an identified defect or contract mismatch."""
    id: str = Field(..., description="Unique bug identifier (e.g., BUG-001)")
    title: str = Field(..., description="Concise summary of the bug")
    description: str = Field(..., description="Detailed description of the failure observed")
    severity: Literal["low", "medium", "high", "critical"] = Field(..., description="Defect severity")
    owning_agent: Literal["frontend", "backend", "both"] = Field(..., description="Specialist responsible for fixing the bug")
    edge_case_category: Literal[
        "empty/zero",
        "negative",
        "huge values",
        "rounding",
        "bad input",
        "contract mismatch",
        "security/validation",
        "other"
    ] = Field(..., description="Category of the edge case or failure")
    suggested_fix: str = Field(..., description="Specific recommendation to resolve the issue")


class QAReport(BaseModel):
    """
    Formal QA Report produced by the QA & Logic Verifier.
    Contains test execution statistics, real pytest outputs, and structured bug entries.
    """
    round_number: int = Field(default=1, description="Verification round index")
    passed: bool = Field(..., description="True if all tests pass and logic is verified without defects")
    summary: str = Field(..., description="Executive summary of QA findings")
    tests_executed: int = Field(default=0, description="Total number of pytest test cases executed")
    tests_passed: int = Field(default=0, description="Count of passed test cases")
    tests_failed: int = Field(default=0, description="Count of failed test cases")
    raw_test_output: str = Field(default="", description="Verbatim stdout/stderr from pytest")
    bugs: List[BugReport] = Field(default_factory=list, description="List of defects found")
    owning_agents_needing_fixes: List[Literal["frontend", "backend"]] = Field(
        default_factory=list,
        description="List of agents who must take corrective action before next QA round"
    )


class RePromptPackage(BaseModel):
    """
    Targeted revision instructions issued by the Orchestrator after a failed QA round.
    Only addresses agents that own identified defects.
    """
    round_number: int = Field(..., description="Round number triggering this re-prompt")
    target_agents: List[Literal["frontend", "backend"]] = Field(..., description="Specialists requiring changes")
    frontend_fixes: Optional[str] = Field(default=None, description="Revised, targeted instructions for Frontend")
    backend_fixes: Optional[str] = Field(default=None, description="Revised, targeted instructions for Backend")
    reasons: str = Field(..., description="Rationale and bug resolution goals")


class FinalSignOff(BaseModel):
    """Final sign-off decision issued by the Orchestrator upon QA approval."""
    approved: bool = Field(..., description="Whether the delivery meets acceptance criteria")
    summary: str = Field(..., description="Final sign-off remarks")
    acceptance_criteria_verified: List[str] = Field(default_factory=list, description="Verified criteria")
    notes: str = Field(default="", description="Deployment or run instructions")
